package lk.aak.agency.control;

import org.apache.poi.ss.usermodel.Row;
import org.apache.poi.ss.usermodel.Sheet;
import org.apache.poi.xssf.usermodel.XSSFWorkbook;

import java.io.ByteArrayOutputStream;
import java.nio.charset.StandardCharsets;
import java.util.List;

/** Made-up reports laid out exactly like the files Connect Plus produces (no real shop or bill data). */
final class ControlFixtures {

    private ControlFixtures() { }

    record Bill(String serial, String outlet, String net, String mode, String cash) { }

    /** RD Sales Entry > Excel: title, date and vehicle, header, one row per bill, a Total row, the footer. */
    static byte[] rdSales(String date, String vehicle, List<Bill> bills) throws Exception {
        try (XSSFWorkbook wb = new XSSFWorkbook(); ByteArrayOutputStream out = new ByteArrayOutputStream()) {
            Sheet sheet = wb.createSheet("Report");
            sheet.createRow(0).createCell(0).setCellValue("RD Sales & Payments Report");
            Row info = sheet.createRow(1);
            info.createCell(0).setCellValue("Date: " + date);
            info.createCell(1).setCellValue("CBL Vehicle: " + vehicle);
            info.createCell(2).setCellValue("Agency Vehicle: " + vehicle);
            String[] heads = {"Serial No", "Beat Name", "Outlet Name", "Gross Amount", "Discount", "Sku Discount", "Dist.Dis Amount", "Fresh Return", "Market Return", "Rebate", "Net Amount", "Payment Mode", "Cash Amt Paid", "Cheque Details"};
            Row h = sheet.createRow(2);
            for (int i = 0; i < heads.length; i++) h.createCell(i).setCellValue(heads[i]);
            int r = 3;
            double total = 0;
            for (Bill b : bills) {
                Row row = sheet.createRow(r++);
                row.createCell(0).setCellValue(b.serial());
                row.createCell(1).setCellValue("SOME BEAT");
                row.createCell(2).setCellValue(b.outlet());
                row.createCell(10).setCellValue(b.net());
                row.createCell(11).setCellValue(b.mode());
                row.createCell(12).setCellValue(b.cash());
                total += Double.parseDouble(b.net());
            }
            Row t = sheet.createRow(r++);
            t.createCell(0).setCellValue("Total");
            t.createCell(10).setCellValue(total);
            sheet.createRow(r).createCell(0).setCellValue("© 2026 - Generated by Connect Plus System");
            wb.write(out);
            return out.toByteArray();
        }
    }

    /** Stocks > Stock Balance Report > CSV button. */
    static byte[] stockCsv(String... rows) {
        StringBuilder sb = new StringBuilder("SKU,Case,Unit,Quantity,Stock Volume (In Kg),Selling Price,Cost Price,Stock Value (Cost),Stock Value (Selling)\n");
        for (String row : rows) {
            String[] p = row.split("\\|");
            String name = p[0].contains(",") ? "\"" + p[0] + "\"" : p[0];
            sb.append(name).append(",0,").append(p[1]).append(',').append(p[1]).append(",1.00,45.00,41.99,100.0000,110.0000\n");
        }
        return sb.toString().getBytes(StandardCharsets.UTF_8);
    }

    /** The same report from the Excel button: a title row first, a totals row (no SKU) last, then the footer. */
    static byte[] stockExcel(String... rows) throws Exception {
        try (XSSFWorkbook wb = new XSSFWorkbook(); ByteArrayOutputStream out = new ByteArrayOutputStream()) {
            Sheet sheet = wb.createSheet("Report");
            sheet.createRow(0).createCell(0).setCellValue("Stock Summary Report");
            String[] heads = {"SKU", "Case", "Unit", "Quantity", "Stock Volume (In Kg)"};
            Row h = sheet.createRow(1);
            for (int i = 0; i < heads.length; i++) h.createCell(i).setCellValue(heads[i]);
            int r = 2;
            for (String row : rows) {
                String[] p = row.split("\\|");
                Row x = sheet.createRow(r++);
                x.createCell(0).setCellValue(p[0]);
                x.createCell(1).setCellValue(0);
                x.createCell(2).setCellValue(Integer.parseInt(p[1]));
                x.createCell(3).setCellValue(Integer.parseInt(p[1]));
            }
            Row total = sheet.createRow(r++);
            total.createCell(1).setCellValue(0);
            total.createCell(3).setCellValue(999);
            sheet.createRow(r).createCell(0).setCellValue("© 2026 - Generated by Connect Plus System");
            wb.write(out);
            return out.toByteArray();
        }
    }
}
